"""The traceability index: what it says, when it is written, and when it is stale.

Realises SPEC-18 (written only after a clean full run, and nothing else) and
SPEC-19 (a stale index fails a check run).
"""

from __future__ import annotations

from pathlib import Path

from spec_check.citations import Citations
from spec_check.tree import Finding, Requirement

INDEX_PATH = Path("specs") / "_traceability.md"


def render_traceability(requirements: list[Requirement], citations: Citations) -> str:
    """Render the generated requirement-to-implementation index."""
    lines = [
        "# Requirement traceability",
        "",
        "Generated by `make spec-check`. Do not edit by hand.",
        "",
    ]
    for spec in sorted({req.spec for req in requirements}):
        lines += [f"## {spec}", "", "| Requirement | Title | Cited by |", "|---|---|---|"]
        for req in sorted((r for r in requirements if r.spec == spec), key=lambda r: r.number):
            cited = ", ".join(f"`{p}`" for p in sorted(citations.get(req.id, ()))) or "—"
            title = req.title
            if req.withdrawn:
                title = f"{title} (withdrawn)"
            elif req.pending:
                title = f"{title} (pending)"
            lines.append(f"| `{req.id}` | {title} | {cited} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def index_sections(text: str) -> dict[str, str]:
    """Split an index into its per-spec `## <spec>` sections."""
    found: dict[str, list[str]] = {}
    current: list[str] | None = None
    for line in text.splitlines():
        if line.startswith("## "):
            current = found.setdefault(line.removeprefix("## ").strip(), [])
        if current is not None:
            current.append(line)
    return {spec: "\n".join(lines).rstrip("\n") for spec, lines in found.items()}


def check_index(root: Path, expected: str, specs: list[str] | None = None) -> list[Finding]:
    """Compare the committed index with `expected`, without writing anything (SPEC-19).

    `specs` limits the comparison to those specs' sections, for a scoped run.
    """
    path = root / INDEX_PATH
    if not path.is_file():
        return [Finding("stale-index", f"{INDEX_PATH} does not exist; run spec-check")]
    actual = path.read_text()
    if specs is None:
        if actual == expected:
            return []
        return [Finding("stale-index", f"{INDEX_PATH} is not current; run spec-check")]
    want, have = index_sections(expected), index_sections(actual)
    return [
        Finding("stale-index", f"{INDEX_PATH} is not current for {spec}; run spec-check")
        for spec in sorted(specs)
        if want.get(spec) != have.get(spec)
    ]


def write_index(root: Path, text: str) -> None:
    """Write the index, the one file the checker writes (SPEC-18)."""
    (root / INDEX_PATH).write_text(text)
